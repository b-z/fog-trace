"""Build web/src/airports.js (IATA code -> coordinates) for the flights page from OurAirports.

    curl -LO https://davidmegginson.github.io/ourairports-data/airports.csv
    python3 tools/build_airports.py airports.csv

OurAirports data is public domain. Closed airports are left out; OVERRIDES fixes codes whose OurAirports entry
still points to a replaced airport.
"""
import csv, os, sys
from datetime import date

OVERRIDES = {
    'PKR': (28.1830, 84.0250),   # Pokhara: flights moved to Pokhara International (opened 2023); OurAirports has the old field
}


def main():
    src = sys.argv[1]
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'web', 'src', 'airports.js')
    rank = {'large_airport': 0, 'medium_airport': 1, 'small_airport': 2, 'seaplane_base': 3, 'heliport': 4}
    best = {}
    for r in csv.DictReader(open(src, encoding='utf-8')):
        code = r['iata_code'].strip().upper()
        if len(code) != 3 or r['type'] not in rank:
            continue
        key = (r['scheduled_service'] != 'yes', rank[r['type']])
        if code not in best or key < best[code][0]:
            best[code] = (key, float(r['latitude_deg']), float(r['longitude_deg']))
    coords = {k: (v[1], v[2]) for k, v in best.items()}
    coords.update(OVERRIDES)
    body = ';'.join(f'{k},{round(la, 4):g},{round(lo, 4):g}' for k, (la, lo) in sorted(coords.items()))
    with open(out, 'w', encoding='utf-8') as f:
        f.write('/* airports.js — IATA code -> [lat, lng] for the flights page. Generated by tools/build_airports.py\n'
                f' * from OurAirports (public domain, https://ourairports.com/data/), {date.today().isoformat()}. Do not edit. */\n'
                '(function (global) {\n'
                f"  var S = '{body}';\n"
                '  var A = {};\n'
                "  S.split(';').forEach(function (e) { var p = e.split(','); A[p[0]] = [+p[1], +p[2]]; });\n"
                '  global.FogAirports = A;\n'
                "})(typeof window !== 'undefined' ? window : globalThis);\n")
    print(f'{len(coords)} airports -> {out} ({os.path.getsize(out)} bytes)')


if __name__ == '__main__':
    main()
